'use client'
import {useState} from 'react'

type Lesson = {payload: string; pin: string}
const rooms = ['C1.3.239', 'C1.2.150', 'C1.1.364']

function pad(n: number) { return String(n).padStart(2, '0') }
function fmt(d: Date) { return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}` }

/** Mirrors LessonService.GenerateQRCode / GeneratePinCode from the repository, with synthetic data. */
function createLesson(room: string): Lesson {
  const start = new Date(); start.setSeconds(0, 0)
  const end = new Date(start.getTime() + 50 * 60000)
  const payload = JSON.stringify({Teacher: 'Demo Teacher', Room: room, Group: 'SE-2401', StartTime: fmt(start), EndTime: fmt(end)}, null, 2)
  const pin = String(1000 + Math.floor(Math.random() * 8999))
  return {payload, pin}
}

export default function AttendanceFlow() {
  const [room, setRoom] = useState(rooms[0])
  const [lesson, setLesson] = useState<Lesson | null>(null)
  const [scanned, setScanned] = useState(false)
  const [entry, setEntry] = useState('')
  const [result, setResult] = useState<'ok' | 'bad' | null>(null)
  const step = !lesson ? 0 : !scanned ? 1 : result === 'ok' ? 3 : 2

  function reset() { setLesson(null); setScanned(false); setEntry(''); setResult(null) }

  return <div className="demo attendance-flow">
    <ol className="steps" aria-label="Walkthrough progress">
      {['Teacher opens lesson', 'Student scans room code', 'Student enters PIN', 'Marked present'].map((s, i) => <li key={s} className={i < step ? 'done' : i === step ? 'now' : ''}><span>{i + 1}</span>{s}</li>)}
    </ol>
    <div className="flow-body">
      {step === 0 && <div className="flow-panel">
        <label className="field-label" htmlFor="room">Room</label>
        <select id="room" value={room} onChange={e => setRoom(e.target.value)}>{rooms.map(r => <option key={r}>{r}</option>)}</select>
        <button className="button primary small" onClick={() => setLesson(createLesson(room))}>Open lesson as teacher</button>
      </div>}
      {lesson && <div className="flow-panel">
        <span className="field-label">QR payload (as generated by LessonService)</span>
        <pre className="console small">{lesson.payload}</pre>
        <p className="pin-line">Lesson PIN shown to the class: <b>{lesson.pin}</b></p>
        {!scanned && <button className="button primary small" onClick={() => setScanned(true)}>Scan as student</button>}
      </div>}
      {scanned && result !== 'ok' && <form className="flow-panel" onSubmit={e => {e.preventDefault(); setResult(entry === lesson?.pin ? 'ok' : 'bad')}}>
        <label className="field-label" htmlFor="pin">Enter the 4-digit PIN</label>
        <div className="pin-row">
          <input id="pin" inputMode="numeric" pattern="[0-9]{4}" maxLength={4} autoComplete="off" value={entry} onChange={e => {setEntry(e.target.value.replace(/\D/g, '')); setResult(null)}} aria-invalid={result === 'bad'} aria-describedby="pin-msg"/>
          <button className="button primary small" type="submit">Confirm</button>
        </div>
        <p id="pin-msg" className={result === 'bad' ? 'msg bad' : 'msg'} aria-live="polite">{result === 'bad' ? 'Wrong PIN. The record is not written.' : 'Try a wrong PIN first: the app refuses it.'}</p>
      </form>}
      {result === 'ok' && <div className="flow-panel success" aria-live="polite">
        <p><b>Present.</b> Record written for {room}, group SE-2401.</p>
        <button className="button ghost small" onClick={reset}>Run again</button>
      </div>}
    </div>
  </div>
}
